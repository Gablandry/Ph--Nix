/* ===========================================================
   Bascule francais / anglais
   Le dictionnaire ci-dessus associe chaque texte francais du
   site a sa version anglaise. Le moteur parcourt la page,
   remplace les textes, et garde l'original en memoire pour
   pouvoir revenir au francais sans recharger.
   =========================================================== */
(function () {
  var CLE = 'phenix-langue';
  var ATTRS = ['alt', 'aria-label', 'title', 'placeholder'];
  var originaux = null;   // rempli au premier passage

  function norm(t) { return t.replace(/\s+/g, ' ').trim(); }

  /* Recense tous les endroits traduisibles, une seule fois. */
  function recenser() {
    if (originaux) return originaux;
    originaux = { textes: [], attributs: [], titre: document.title, meta: null };

    var promeneur = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode;
        if (!p) return NodeFilter.FILTER_REJECT;
        var b = p.nodeName;
        if (b === 'SCRIPT' || b === 'STYLE' || b === 'NOSCRIPT') return NodeFilter.FILTER_REJECT;
        return norm(n.nodeValue) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var n;
    while ((n = promeneur.nextNode())) {
      originaux.textes.push({ noeud: n, fr: n.nodeValue });
    }

    ATTRS.forEach(function (a) {
      var els = document.querySelectorAll('[' + a + ']');
      for (var i = 0; i < els.length; i++) {
        originaux.attributs.push({ el: els[i], attr: a, fr: els[i].getAttribute(a) });
      }
    });

    var m = document.querySelector('meta[name="description"]');
    if (m) originaux.meta = { el: m, fr: m.getAttribute('content') };

    return originaux;
  }

  /* Remplace en gardant les espaces d'origine autour du texte. */
  function traduire(brut) {
    var cle = norm(brut);
    var en = DICO[cle];
    if (!en) return null;
    var avant = brut.match(/^\s*/)[0];
    var apres = brut.match(/\s*$/)[0];
    return avant + en + apres;
  }

  function appliquer(langue) {
    var o = recenser();
    var versAnglais = (langue === 'en');

    o.textes.forEach(function (t) {
      if (versAnglais) {
        var en = traduire(t.fr);
        if (en !== null) t.noeud.nodeValue = en;
      } else {
        t.noeud.nodeValue = t.fr;
      }
    });

    o.attributs.forEach(function (a) {
      if (versAnglais) {
        var en = traduire(a.fr);
        if (en !== null) a.el.setAttribute(a.attr, en);
      } else {
        a.el.setAttribute(a.attr, a.fr);
      }
    });

    document.title = versAnglais ? (DICO[norm(o.titre)] || o.titre) : o.titre;
    if (o.meta) {
      o.meta.el.setAttribute('content',
        versAnglais ? (DICO[norm(o.meta.fr)] || o.meta.fr) : o.meta.fr);
    }

    document.documentElement.lang = versAnglais ? 'en' : 'fr';
    document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.classList.toggle('actif', b.dataset.langue === langue);
    });
    try { localStorage.setItem(CLE, langue); } catch (e) {}
  }

  window.choisirLangue = appliquer;

  function demarrer() {
    var choisie = 'fr';
    try { choisie = localStorage.getItem(CLE) || 'fr'; } catch (e) {}
    if (choisie === 'en') appliquer('en');
    else document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.classList.toggle('actif', b.dataset.langue === 'fr');
    });

    document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.addEventListener('click', function () { appliquer(b.dataset.langue); });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', demarrer);
  } else {
    demarrer();
  }
})();
